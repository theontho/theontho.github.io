#!/usr/bin/env python3
"""Render the 1200×630 social preview images (Open Graph / Twitter cards).

Usage:
    uv run --with playwright scripts/social_previews.py [site] [may] [nov] [aligners] [projects]

With no arguments everything is rendered. Each card is an HTML template in
scripts/social/ filled from the site's data files and screenshotted in headless
Chrome or Chromium into assets/social/<name>.jpg.

`projects` makes one share page per project, p/<id>/index.html, because
crawlers don't run the front page's JavaScript: sharing /?project=<id> can only
show the site's card, while /p/<id>/ shows the project's own card and then
sends visitors on to /?project=<id>. A project with its own page on the site
(`"page"` in data/projects.json) reuses that page's card; the others get
assets/social/projects/<id>.jpg. Pages and cards of removed projects are deleted.

Look at the images before committing them. Exits with status 3 when Playwright
or a browser is missing, so callers (the shootout publisher) can skip gracefully.
"""

from __future__ import annotations

import html
import json
import re
import shutil
import sys
import tempfile
from pathlib import Path
from string import Template

ROOT = Path(__file__).resolve().parent.parent
TEMPLATES = ROOT / "scripts" / "social"
OUT = ROOT / "assets" / "social"
WIDTH, HEIGHT = 1200, 630
MAX_BYTES = 300_000
CARDS = {
    "site": "site.jpg",
    "may": "gui-for-cli-may.jpg",
    "nov": "gui-for-cli-2026-11.jpg",
    "aligners": "apple-silicon-aligners.jpg",
}
SITE_URL = "https://theontho.github.io/"
SITE_NAME = "Mahyar (Mac) McDonald"
SHARE_DIR = ROOT / "p"
PROJECT_CARDS = OUT / "projects"
GENERATED = "<!-- Generated by scripts/social_previews.py from data/projects.json; edit that, not this file. -->"
SKIP = 3
SITE_MOSAIC = ["wgsextract-cli", "dawnbreakers", "apple-silicon-aligners", "ffmi-calculator", "sheprd", "pi-browser"]


def load(rel: str) -> dict:
    return json.loads((ROOT / rel).read_text())


def score_class(value: float) -> str:
    return f"s{min(5, max(1, int(value + 0.5)))}"  # round half up, like the page


def tile(src: str, label: str | None = None, score: float | None = None) -> str:
    caption = ""
    if label:
        badge = f'<span class="score {score_class(score)}">{score:g}</span>' if score is not None else ""
        caption = f"<figcaption>{badge}{html.escape(label)}</figcaption>"
    return f'<figure class="sc-tile"><img src="{html.escape(src)}" alt="">{caption}</figure>'


def site_card() -> dict:
    data = load("data/projects.json")
    first = {p["id"]: p["screenshots"][0]["src"] for p in data["projects"] if p.get("screenshots")}
    shots = [first[i] for i in SITE_MOSAIC if i in first]
    shots += [s for s in first.values() if s not in shots]
    return {
        "name": html.escape(data["profile"]["name"]),
        "subtitle": "Genomics tools, games, home-lab automation and local-AI pipelines.",
        "count": len(data["projects"]),
        "tiles": "".join(tile(s) for s in shots[:6]),
    }


def may_card() -> dict:
    surfaces = load("data/gui-for-cli-eval.json")["surfaces"]
    rated = sorted(
        (s for s in surfaces if isinstance(s.get("visual"), int) and s.get("screenshot")),
        key=lambda s: (-s["visual"], s["name"]),
    )
    # An even spread from best to worst, so the grid shows the range of ratings.
    picks = [rated[round(i * (len(rated) - 1) / 8)] for i in range(9)]
    return {
        "mean": "2.55",
        "rated": sum(1 for s in surfaces if s.get("screenshot")),
        "tiles": "".join(tile(s["screenshot"], s["name"], s["visual"]) for s in picks),
    }


def nov_card() -> dict:
    data = load("data/gui-for-cli-shootout-2026-11.json")
    stats = data["stats"]

    def best(t: dict) -> float | None:
        return next((t[k] for k in ("userVisual", "myVisual", "selfVisual") if t.get(k) is not None), None)

    done = sorted(
        (t for t in data["toolkits"] if t["status"] == "done" and t["shots"]),
        key=lambda t: (-(best(t) or 0), t["name"]),
    )
    key, label = next(
        (
            (k, lbl)
            for k, lbl in (
                ("userVisual", "owner rating"),
                ("myVisual", "supervisor visual"),
                ("selfVisual", "self-rated visual"),
            )
            if stats["vsMay"][k]["n"]
        ),
        ("selfVisual", "self-rated visual"),
    )
    compare = stats["vsMay"][key]
    fmt = lambda v: "–" if v is None else f"{v:.1f}"
    count = 12 if len(done) > 9 else 9 if len(done) > 4 else 4
    return {
        "done": stats["done"],
        "total": stats["total"],
        "done_pct": round(100 * stats["done"] / stats["total"], 1),
        "building_pct": round(100 * stats["building"] / stats["total"], 1),
        "now": fmt(compare["newMean"]),
        "now_label": label,
        "may": fmt(compare["mayMean"]),
        "columns": 4 if count == 12 else 3 if count == 9 else 2,
        "tiles": "".join(tile(t["shots"][0]["src"], t["name"], best(t)) for t in done[:count]),
    }


def aligners_card() -> dict:
    data = load("data/apple-silicon-aligners.json")
    stats = "".join(
        f'<div class="sc-stat{" sc-hi" if i == 0 else ""}"><b>{html.escape(x["value"])}</b>'
        f"<span>{html.escape(x['label'].split(' (')[0])}</span></div>"
        for i, x in enumerate(data["headline"][:3])
    )
    charts = "".join(
        f'<figure class="sc-chart"><img src="screenshots/apple-silicon-aligners/{name}.webp" alt=""></figure>'
        for name in ("hillclimb", "energy")
    )
    return {"period": "November 2026", "title": html.escape(data["title"]), "stats": stats, "charts": charts}


def mono(p: dict) -> str:
    initials = "".join(w[0] for w in re.findall(r"[A-Za-z0-9]+", p["name"])[:2]).upper()
    tags = "".join(f"<span>{html.escape(x)}</span>" for x in (p.get("tech") or [])[:6])
    return f'<div class="sc-mono"><b>{html.escape(initials)}</b><div class="sc-tags">{tags}</div></div>'


def hue(text: str) -> str:
    # The same hue as the front page's placeholder thumbnails (assets/site.js).
    n = 0
    for c in text:
        n = (n * 31 + ord(c)) % 360
    return f"hsl({n} 70% 55%)"


def project_card(p: dict, config: dict) -> dict:
    shots = [s["src"] for s in p.get("screenshots", [])]
    visual = "".join(tile(s) for s in shots[:4]) if len(shots) >= 4 else tile(shots[0]) if shots else mono(p)
    category = next(c["title"] for c in config["categories"] if c["id"] == p["category"])
    name = p["name"]
    return {
        "text_width": 560 if shots else 600,
        "title_size": 60 if len(name) <= 24 else 52 if len(name) <= 40 else 44,
        "columns": 2 if len(shots) >= 4 else 1,
        "hue": hue(name),
        "category": html.escape(category),
        "status": p["status"],
        "status_label": html.escape(config["statuses"][p["status"]]["label"]),
        "when": f'<span class="sc-chip">{html.escape(p["when"])}</span>' if p.get("when") else "",
        "name": html.escape(name),
        "summary": html.escape(p["summary"]),
        "visual": visual,
    }


BUILDERS = {"site": site_card, "may": may_card, "nov": nov_card, "aligners": aligners_card}


def launch(pw, error: type[Exception]):
    """Chrome if installed, else a system Chromium, else Playwright's own build."""
    paths = [p for name in ("chromium", "chromium-browser", "google-chrome") if (p := shutil.which(name))]
    options = [{"channel": "chrome"}, *({"executable_path": p} for p in paths), {}]
    for i, option in enumerate(options):
        try:
            return pw.chromium.launch(headless=True, **option)
        except error:
            if i == len(options) - 1:
                raise
    return None


def render(page, name: str, values: dict | None = None, out: Path | None = None) -> Path:
    template = "project" if values is not None else name
    body = Template((TEMPLATES / f"{template}.html").read_text()).substitute(values or BUILDERS[name]())
    body = body.replace("<head>", f'<head><base href="{ROOT.as_uri()}/">', 1)
    with tempfile.NamedTemporaryFile("w", suffix=".html", delete=False) as f:
        f.write(body)
    try:
        page.goto(Path(f.name).as_uri(), wait_until="load")
        page.evaluate("document.fonts.ready")
    finally:
        Path(f.name).unlink()
    out = out or OUT / CARDS[name]
    out.parent.mkdir(parents=True, exist_ok=True)
    for quality in (90, 86, 82, 78, 74, 70):
        image = page.screenshot(type="jpeg", quality=quality)
        if len(image) <= MAX_BYTES:
            break
    out.write_bytes(image)
    print(f"{out.relative_to(ROOT)}: {len(image) // 1024} KB (quality {quality})")
    return out


def esc(text: str) -> str:
    return html.escape(text, quote=True)


def page_card(url: str) -> str | None:
    """The og:image of one of the site's own pages, if the URL is one."""
    if re.match(r"[a-z]+:", url):
        return None
    page = ROOT / url
    if page.is_dir():
        page = page / "index.html"
    if not page.is_file():
        return None
    m = re.search(r'<meta property="og:image" content="([^"]+)"', page.read_text())
    return m.group(1) if m else None


def meta_tags(url: str, title: str, description: str, image: str, alt: str) -> str:
    return "\n".join(
        f"  {line}"
        for line in (
            '<meta property="og:type" content="website">',
            f'<meta property="og:site_name" content="{esc(SITE_NAME)}">',
            f'<meta property="og:url" content="{esc(url)}">',
            f'<meta property="og:title" content="{esc(title)}">',
            f'<meta property="og:description" content="{esc(description)}">',
            f'<meta property="og:image" content="{esc(image)}">',
            '<meta property="og:image:type" content="image/jpeg">',
            '<meta property="og:image:width" content="1200">',
            '<meta property="og:image:height" content="630">',
            f'<meta property="og:image:alt" content="{esc(alt)}">',
            '<meta name="twitter:card" content="summary_large_image">',
            f'<meta name="twitter:title" content="{esc(title)}">',
            f'<meta name="twitter:description" content="{esc(description)}">',
            f'<meta name="twitter:image" content="{esc(image)}">',
            f'<meta name="twitter:image:alt" content="{esc(alt)}">',
        )
    )


def share_page(p: dict, image: str) -> str:
    target = f"../../?project={p['id']}"
    alt = f"{p['name']}: {p['summary']}"
    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  {GENERATED}
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{esc(p["name"])} · {esc(SITE_NAME)}</title>
  <meta name="description" content="{esc(p["summary"])}">
  <meta name="robots" content="noindex">
{meta_tags(f"{SITE_URL}p/{p['id']}/", p["name"], p["summary"], image, alt)}
  <meta name="color-scheme" content="dark light">
  <link rel="icon" href="../../assets/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="../../assets/site.css">
  <script>location.replace({json.dumps(target)});</script>
</head>
<body>
  <header class="hero">
    <div class="wrap">
      <p class="eyebrow"><a href="../../">Project showcase</a></p>
      <h1>{esc(p["name"])}</h1>
      <p class="tagline">{esc(p["summary"])}</p>
      <p><a href="{esc(target)}">Open {esc(p["name"])} in the project showcase →</a></p>
    </div>
  </header>
</body>
</html>
"""


def projects(page) -> None:
    config = load("data/projects.json")
    public = [p for p in config["projects"] if not p.get("private")]
    keep_pages, keep_cards = set(), set()
    for p in public:
        image = page_card(p["page"]) if p.get("page") else None
        if image is None:
            out = render(page, p["id"], project_card(p, config), PROJECT_CARDS / f"{p['id']}.jpg")
            keep_cards.add(out)
            image = SITE_URL + out.relative_to(ROOT).as_posix()
        dest = SHARE_DIR / p["id"] / "index.html"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(share_page(p, image))
        keep_pages.add(dest.parent)
    for d in SHARE_DIR.iterdir() if SHARE_DIR.is_dir() else []:
        index = d / "index.html"
        if d not in keep_pages and index.is_file() and GENERATED in index.read_text():
            shutil.rmtree(d)
            print(f"removed {d.relative_to(ROOT)}")
    for img in PROJECT_CARDS.glob("*.jpg") if PROJECT_CARDS.is_dir() else []:
        if img not in keep_cards:
            img.unlink()
            print(f"removed {img.relative_to(ROOT)}")
    print(f"{len(keep_pages)} share pages in p/, {len(keep_cards)} project cards")


def main() -> int:
    names = sys.argv[1:] or [*CARDS, "projects"]
    if unknown := [n for n in names if n not in CARDS and n != "projects"]:
        print(f"unknown card {unknown}; choose from {', '.join(CARDS)}, projects", file=sys.stderr)
        return 2
    try:
        from playwright.sync_api import Error, sync_playwright
    except ImportError:
        print("playwright is not installed; skipping social previews", file=sys.stderr)
        return SKIP
    with sync_playwright() as pw:
        try:
            browser = launch(pw, Error)
        except Error as err:
            print(f"no headless browser available ({err}); skipping social previews", file=sys.stderr)
            return SKIP
        page = browser.new_page(viewport={"width": WIDTH, "height": HEIGHT}, color_scheme="dark")
        # The page cards first: share pages reuse them.
        for name in names:
            if name != "projects":
                render(page, name)
        if "projects" in names:
            projects(page)
        browser.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
